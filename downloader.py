"""
downloader.py — تحميل الفيديوهات من المواقع المحمية بـ Cloudflare

استراتيجيات متعددة (بالترتيب):
  1. yt-dlp مع impersonate + cookies
  2. curl_cffi مع impersonate
  3. FlareSolverr (يحل التحدي عبر متصفح حقيقي)
  4. curl_cffi + الكوكيز من FlareSolverr

يرفع DownloadError عند فشل كل الاستراتيجيات.
"""

